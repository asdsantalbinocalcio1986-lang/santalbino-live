-- Sant'Albino Live: database, accesso amministratore singolo, voti MVP e archivio immagini.
-- Prima di eseguire: sostituire l'indirizzo segnaposto con l'email ESATTA dell'unico utente
-- già creato in Supabase > Authentication > Users. Non usare mai la service_role nel browser.

create table if not exists public.live_state (
  id integer primary key check (id = 1),
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.santalbino_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.santalbino_admins enable row level security;

create or replace function public.is_santalbino_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.santalbino_admins
    where user_id = auth.uid()
  );
$$;
revoke all on function public.is_santalbino_admin() from public;
grant execute on function public.is_santalbino_admin() to anon, authenticated;

-- Imposta l'unico amministratore tramite email. Se l'email non corrisponde a un solo
-- utente, lo script si interrompe senza concedere accessi in modo permissivo.
do $$
declare
  admin_email text := 'INSERISCI_EMAIL_AMMINISTRATORE';
  found_user_id uuid;
  found_count integer;
begin
  if admin_email = 'INSERISCI_EMAIL_AMMINISTRATORE' or position('@' in admin_email) = 0 then
    raise exception 'Modifica admin_email nello script con l''email esatta dell''unico amministratore.';
  end if;
  select count(*) into found_count
  from auth.users
  where lower(email) = lower(admin_email);
  if found_count <> 1 then
    raise exception 'Atteso un solo utente Supabase con questa email; trovati: %.', found_count;
  end if;
  select id into found_user_id
  from auth.users
  where lower(email) = lower(admin_email);
  delete from public.santalbino_admins where user_id <> found_user_id;
  insert into public.santalbino_admins(user_id)
  values (found_user_id)
  on conflict (user_id) do nothing;
end $$;

alter table public.live_state enable row level security;
-- Elimina anche eventuali policy permissive create in precedenza dal pannello.
do $$
declare p record;
begin
  for p in
    select tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('live_state','mvp_votes')
  loop
    execute format('drop policy if exists %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;
drop policy if exists "Public can read live state" on public.live_state;
create policy "Public can read live state"
  on public.live_state for select to anon, authenticated using (true);
drop policy if exists "Authenticated admins can insert live state" on public.live_state;
drop policy if exists "Authenticated admins can update live state" on public.live_state;
drop policy if exists "Only the designated admin can insert live state" on public.live_state;
create policy "Only the designated admin can insert live state"
  on public.live_state for insert to authenticated
  with check (public.is_santalbino_admin());
drop policy if exists "Only the designated admin can update live state" on public.live_state;
create policy "Only the designated admin can update live state"
  on public.live_state for update to authenticated
  using (public.is_santalbino_admin())
  with check (public.is_santalbino_admin());

