create table if not exists public.mvp_votes (
  id bigint generated by default as identity primary key,
  match_key text not null,
  voter_hash text not null,
  candidate_key text not null,
  candidate_name text not null,
  team text not null check (team in ('home','away')),
  shirt_number text,
  created_at timestamptz not null default now(),
  constraint mvp_votes_one_per_voter unique (match_key, voter_hash)
);
create index if not exists mvp_votes_match_key_idx on public.mvp_votes(match_key);
alter table public.mvp_votes enable row level security;
drop policy if exists "Public can read MVP votes" on public.mvp_votes;
create policy "Public can read MVP votes"
  on public.mvp_votes for select to anon, authenticated using (true);
drop policy if exists "Public can cast MVP vote" on public.mvp_votes;
create policy "Public can cast MVP vote"
  on public.mvp_votes for insert to anon, authenticated
  with check (
    length(match_key) between 1 and 180
    and length(voter_hash) between 16 and 100
    and length(candidate_key) between 1 and 180
    and length(candidate_name) between 1 and 120
  );

-- Bucket pubblico in lettura (le grafiche devono essere visibili ai tifosi),
-- ma scrittura e cancellazione riservate all'unico amministratore.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('santalbino-media', 'santalbino-media', true, 8388608,
        array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = true,
  file_size_limit = 8388608,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can view SantAlbino media" on storage.objects;
create policy "Public can view SantAlbino media"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'santalbino-media');
drop policy if exists "Only SantAlbino admin can upload media" on storage.objects;
create policy "Only SantAlbino admin can upload media"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'santalbino-media' and public.is_santalbino_admin());
drop policy if exists "Only SantAlbino admin can update media" on storage.objects;
create policy "Only SantAlbino admin can update media"
  on storage.objects for update to authenticated
  using (bucket_id = 'santalbino-media' and public.is_santalbino_admin())
  with check (bucket_id = 'santalbino-media' and public.is_santalbino_admin());
drop policy if exists "Only SantAlbino admin can delete media" on storage.objects;
create policy "Only SantAlbino admin can delete media"
  on storage.objects for delete to authenticated
  using (bucket_id = 'santalbino-media' and public.is_santalbino_admin());

-- Abilita Realtime solo se le tabelle non sono già nella publication.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'live_state'
  ) then
    alter publication supabase_realtime add table public.live_state;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'mvp_votes'
  ) then
    alter publication supabase_realtime add table public.mvp_votes;
  end if;
end $$;
